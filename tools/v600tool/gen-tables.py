#!/usr/bin/env python3
"""Generate v600_tables_400.h from replay scripts: a 400 dpi scan at y=30 mm
(c400.seq) and a scan close to the top edge (r800y0.seq, short ramp)."""
import sys
L = [l.split() for l in open(sys.argv[1])]
L = [l for l in L if l and not (l[0] == 'P' and L.index(l) == 0)]
def after(header, nth=1):
    hits = [i for i, s in enumerate(L) if s[0] == 'W' and s[1] == header]
    return L[hits[nth - 1] + 1][1]
def arr(name, h):
    b = bytes.fromhex(h)
    s = 'static const unsigned char %s[%d] = {\n' % (name, len(b))
    for i in range(0, len(b), 16):
        s += '    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',\n'
    return s + '};\n\n'
out = ('// Constant tables for 400 dpi flatbed scans, taken from a USB capture of\n'
       "// the scanner's normal operation (protocol data, no driver code).\n"
       '// Generated by tools/v600tool/gen-tables.py from a capture of a 400 dpi scan.\n#pragma once\n\n')
out += arr('kTable07', after('0700000000000100'))
out += arr('kMotorPrefeed400', after('0500000102000600', 1))
out += arr('kMotorScan400', after('0500000102000600', 2))
L = [l.split() for l in open(sys.argv[2])]
L = [l for l in L if l]
out += arr('kMotorPrefeedShort', after('0500000102000200'))
sys.stdout.write(out)
